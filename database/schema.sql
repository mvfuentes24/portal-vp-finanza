-- =====================================================================
-- Portal VP de Finanzas — Esquema de base de datos
-- Motor: PostgreSQL 15+
-- Ejecutar como el usuario de la aplicación sobre la BD portal_finanzas:
--   psql -U portal_app -d portal_finanzas -f database/schema.sql
-- =====================================================================

SET client_encoding = 'UTF8';

BEGIN;

-- =====================================================================
-- 1. ESTRUCTURA ORGANIZACIONAL DE LA VP DE FINANZAS
-- =====================================================================

CREATE TABLE paises (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE departamentos (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL UNIQUE,
    descripcion  VARCHAR(255)
);

-- Catálogo de niveles de seniority
CREATE TABLE niveles (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE
);

-- Un cargo tiene un nivel y pertenece a un departamento.
-- departamento_id es NULL solo para el cargo de Vicepresidente de Finanzas,
-- que dirige la Vicepresidencia completa y está por encima de los departamentos.
CREATE TABLE cargos (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    nivel_id         INTEGER NOT NULL REFERENCES niveles(id),
    departamento_id  INTEGER REFERENCES departamentos(id),
    UNIQUE (nombre, departamento_id)
);

-- Catálogo de funciones
CREATE TABLE funciones (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion  VARCHAR(255) NOT NULL UNIQUE
);

-- Relación muchos a muchos: un cargo tiene varias funciones
-- y una función puede pertenecer a varios cargos
CREATE TABLE cargo_funciones (
    cargo_id    INTEGER NOT NULL REFERENCES cargos(id) ON DELETE CASCADE,
    funcion_id  INTEGER NOT NULL REFERENCES funciones(id),
    PRIMARY KEY (cargo_id, funcion_id)
);

-- El departamento del colaborador se obtiene a través de su cargo
CREATE TABLE colaboradores (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(80)  NOT NULL,
    apellido       VARCHAR(80)  NOT NULL,
    correo         VARCHAR(150) NOT NULL UNIQUE CHECK (correo LIKE '%_@_%'),
    pais_id        INTEGER NOT NULL REFERENCES paises(id),
    fecha_ingreso  DATE NOT NULL,
    estado         VARCHAR(10) NOT NULL DEFAULT 'activo'
                   CHECK (estado IN ('activo', 'inactivo')),
    cargo_id       INTEGER NOT NULL REFERENCES cargos(id)
);

-- =====================================================================
-- 2. ACCESO AL PORTAL
-- =====================================================================

-- Credenciales separadas de los datos del colaborador.
-- El inicio de sesión se hace con el correo del colaborador.
CREATE TABLE usuarios (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id  INTEGER NOT NULL UNIQUE REFERENCES colaboradores(id),
    password_hash   VARCHAR(255) NOT NULL,
    rol             VARCHAR(20) NOT NULL
                    CHECK (rol IN ('administrador', 'jefe_departamento', 'colaborador')),
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 3. MÓDULO DE CIERRES DE CAJA (gestionado por Contraloría)
-- =====================================================================

CREATE TABLE tiendas (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100) NOT NULL UNIQUE,
    pais_id  INTEGER NOT NULL REFERENCES paises(id)
);

CREATE TABLE cajeros (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL,
    tienda_id  INTEGER NOT NULL REFERENCES tiendas(id)
);

-- tienda_id se registra en el cierre porque un cajero podría
-- cubrir otra tienda; el cierre refleja dónde ocurrió realmente.
-- registrado_por es NULL en los cierres cargados desde el dataset inicial.
CREATE TABLE cierres_caja (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id        INTEGER NOT NULL REFERENCES tiendas(id),
    cajero_id        INTEGER NOT NULL REFERENCES cajeros(id),
    fecha            DATE NOT NULL,
    monto_declarado  NUMERIC(12,2) NOT NULL CHECK (monto_declarado >= 0),
    monto_sistema    NUMERIC(12,2) NOT NULL CHECK (monto_sistema >= 0),
    registrado_por   INTEGER REFERENCES usuarios(id),
    registrado_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Estado ACTUAL de cada alerta. Un cierre puede tener varias alertas,
-- pero no dos del mismo tipo.
CREATE TABLE alertas (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cierre_id   INTEGER NOT NULL REFERENCES cierres_caja(id),
    tipo        VARCHAR(20) NOT NULL
                CHECK (tipo IN ('fuera_rango', 'transposicion', 'reincidencia', 'cierre_multiple')),
    detalle     VARCHAR(255),
    estado      VARCHAR(12) NOT NULL DEFAULT 'pendiente'
                CHECK (estado IN ('pendiente', 'revisada', 'descartada')),
    creada_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (cierre_id, tipo)
);

-- Cada cambio de estado de una alerta: quién, cuándo, de qué a qué y por qué.
-- usuario_id es NULL cuando la acción la realiza el sistema (creación automática).
CREATE TABLE alertas_historial (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id        INTEGER NOT NULL REFERENCES alertas(id),
    estado_anterior  VARCHAR(12)
                     CHECK (estado_anterior IN ('pendiente', 'revisada', 'descartada')),
    estado_nuevo     VARCHAR(12) NOT NULL
                     CHECK (estado_nuevo IN ('pendiente', 'revisada', 'descartada')),
    usuario_id       INTEGER REFERENCES usuarios(id),
    comentario       VARCHAR(255),
    fecha            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 4. ÍNDICES para las consultas más frecuentes
-- =====================================================================

CREATE INDEX idx_cargos_departamento     ON cargos (departamento_id);
CREATE UNIQUE INDEX uq_cargo_sin_departamento ON cargos ((departamento_id IS NULL))
    WHERE departamento_id IS NULL;
CREATE INDEX idx_colaboradores_cargo     ON colaboradores (cargo_id);
CREATE INDEX idx_cierres_cajero_fecha    ON cierres_caja (cajero_id, fecha);
CREATE INDEX idx_alertas_estado          ON alertas (estado);
CREATE INDEX idx_historial_alerta        ON alertas_historial (alerta_id);

COMMIT;